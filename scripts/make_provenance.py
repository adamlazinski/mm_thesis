"""
make_provenance.py
==================
Build thesis/provenance.md: for every experiment, the commit that produced its
committed results and which engine corrections that commit was on the right
side of.

    python scripts/make_provenance.py

The thesis has three dated engine corrections that split its results into eras,
and the eras matter more than the dates:

  2026-06-11  24a687f  taker-on-arrival: an order marketable when it reaches
                       the venue is a taker, bypasses the queue and pays the
                       taker fee. Results before this overstate maker fills.
  2026-06-16  8a3d8e7  GLFT closed form: gamma and kappa had been exchanged in
                       the IMPLEMENTATION. Only affects the GLFT code path.
  2026-11-19  ae928b4  terminal accounting: a day's residual position was
                       valued at the final mid rather than crossed out.

An experiment's results are trustworthy for a given claim only if they were
generated after the corrections that bear on that claim. This script states
which side of each line every experiment falls on, from git rather than from
memory.
"""
from __future__ import annotations

import glob
import os
import re
import subprocess
import sys
from datetime import datetime

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "thesis", "provenance.md")

FIXES = [
    ("2026-06-11", "24a687f", "taker-on-arrival",
     "orders marketable on arrival are takers, not makers"),
    ("2026-06-16", "8a3d8e7", "GLFT closed form",
     "gamma/kappa exchanged in the implementation (GLFT path only)"),
    ("2026-11-19", "ae928b4", "terminal accounting",
     "day-end residual crossed out rather than marked at the mid"),
]


def sh(*args):
    return subprocess.run(args, cwd=ROOT, capture_output=True, text=True).stdout.strip()


def data_tier(expdir):
    """
    Which data tier an experiment reads: the purchased CoinAPI history, the
    original live capture, or both. Read from the experiment's own config
    (`data_dir`) where it has one, falling back to static inspection of its
    scripts. An em-dash means neither could be determined, which is true of a
    handful of pure-analysis experiments that consume another experiment's
    output rather than raw data.
    """
    import json as _json
    tiers = set()
    d = os.path.join(ROOT, "experiments", expdir)
    for cfg in glob.glob(os.path.join(d, "*.json")):
        if os.sep + "results" in cfg:
            continue
        try:
            j = _json.load(open(cfg))
        except Exception:
            continue
        dd = j.get("data_dir") if isinstance(j, dict) else None
        if dd:
            tiers.add("purchased" if "real" in dd else "capture")
    for py in glob.glob(os.path.join(d, "*.py")):
        t = open(py, errors="ignore").read()
        if "live" in t and "processed" in t:
            tiers.add("capture")
        if "data/real" in t or '"real"' in t:
            tiers.add("purchased")
    return " + ".join(sorted(tiers)) if tiers else "—"


def last_commit(path):
    """(sha, iso-date, subject) of the last commit touching path."""
    out = sh("git", "log", "-1", "--format=%h\t%ad\t%s", "--date=short", "--", path)
    return out.split("\t") if out else None


def main():
    exps = sorted(
        (d for d in os.listdir(os.path.join(ROOT, "experiments"))
         if os.path.isdir(os.path.join(ROOT, "experiments", d)) and re.match(r"\d+_", d)),
        key=lambda d: (int(d.split("_")[0]), d))

    rows = []
    for d in exps:
        rel = f"experiments/{d}"
        res = None
        for cand in (f"{rel}/results", rel):
            if os.path.isdir(os.path.join(ROOT, cand)):
                res = last_commit(cand)
                if res:
                    break
        code = last_commit(f"{rel}")
        if not res:
            continue
        sha, date, subj = res[0], res[1], res[2]
        rows.append((d, sha, date, subj, code[1] if code else date))

    L = []
    W = L.append
    W("# Experiment Provenance\n")
    W("Generated by `scripts/make_provenance.py`. For each experiment: the commit whose tree "
      "contains its current results, and which of the engine corrections below that commit "
      "post-dates. Built from git, not from memory.\n")
    W("## The corrections that split the results into eras\n")
    W("| date | commit | correction | what was wrong |")
    W("|---|---|---|---|")
    for date, sha, name, what in FIXES:
        W(f"| {date} | `{sha}` | **{name}** | {what} |")
    W("\nAn experiment's results bear on a claim only if they were generated after the "
      "corrections relevant to that claim. The GLFT line affects only the GLFT code path — the "
      "A-S path is a separate implementation that never evaluates that expression — so Part I's "
      "headline is unaffected by it. The taker-on-arrival line affects every maker result. The "
      "terminal-accounting line affects only the two round-trip simulators of Part II.\n")

    W("\n## Per experiment\n")
    W("`data` is the tier the experiment reads: the purchased CoinAPI history (Part I) or the "
      "original live capture (Part II). Together with the commit column this is the "
      "experiment-to-data-to-code chain for every result in the thesis.\n")
    W("| experiment | data | results commit | date | " +
      " | ".join(f"after {n}?" for _, _, n, _ in FIXES) + " |")
    W("|---|---|---|---|" + "---|" * len(FIXES))
    counts = {n: [0, 0] for _, _, n, _ in FIXES}
    tiers = {}
    for d, sha, date, subj, cdate in rows:
        cells = []
        for fdate, _, name, _ in FIXES:
            after = date >= fdate
            counts[name][0 if after else 1] += 1
            cells.append("yes" if after else "**no**")
        t = data_tier(d)
        tiers[t] = tiers.get(t, 0) + 1
        W(f"| `{d}` | {t} | `{sha}` | {date} | " + " | ".join(cells) + " |")
    W("")
    W(f"**{len(rows)} experiments.** Counts after / before each correction: " +
      "; ".join(f"{n} {v[0]}/{v[1]}" for n, v in counts.items()) + ". "
      "By data tier: " + ", ".join(f"{k} {v}" for k, v in sorted(tiers.items())) + ".\n")

    W("\n## How to read a 'no'\n")
    W("A `no` is not automatically a defect — it means the result predates that correction and "
      "has to be checked against it, or scoped. Three cases arise in this thesis and all three "
      "are stated where they occur:\n")
    W("- **GLFT experiments 07-11, 27, 33, 34, 63, 64** predate the closed-form fix. "
      "Contribution 17's addendum reruns the decisive one (experiment 117) on the corrected "
      "formula and reports both; the conclusion strengthens.\n"
      "- **Maker experiments before 2026-06-11** predate taker-on-arrival and overstate maker "
      "fills. The queue-priority verdict was re-established on the corrected engine in "
      "experiment 62, which is what Chapters 5 and 6 cite.\n"
      "- **Experiments 103 and 111** were re-run on 2026-11-19 under the corrected terminal "
      "accounting, and both the old and new figures are reported in Chapter 8 §4.\n")
    W("\nWhere a chapter cites a pre-correction result without a rerun, it says so in text. "
      "This table exists so that claim can be audited rather than taken on trust.\n")

    open(OUT, "w").write("\n".join(L) + "\n")
    print("\n".join(L[:12]))
    print(f"\n... wrote {len(rows)} rows -> {OUT}")


if __name__ == "__main__":
    main()
