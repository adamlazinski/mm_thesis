"""
make_intervals.py
=================
Interval estimates for every headline quantity in the thesis, from the
committed experiment JSONs. Writes thesis/intervals.md.

    python scripts/make_intervals.py

Each row states the point estimate the chapters quote, a 95% percentile
bootstrap interval computed with the right unit of replication, and the n that
interval is built from. Nothing here re-runs a backtest; this reads the series
that already exist and asks how much they support.
"""
