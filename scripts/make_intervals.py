def daily_pnl(*dirs):
    """Daily total_pnl series from one or more run directories, date-ordered."""
    rows = []
    for d in dirs:
        for f in glob.glob(os.path.join(ROOT, d, "*.json")):
            if "_gaps" in f:
                continue
            j = json.load(open(f))
            if isinstance(j, dict) and "total_pnl" in j and "date" in j:
                rows.append((j["date"], j["total_pnl"]))
    rows.sort()
    return [p for _, p in rows], [d for d, _ in rows]


def exp103(key="rt_bps_liq", cfg="none"):
    """(values, coin) for the 30 coin-days of exp 103."""
    v, c = [], []
    for f in sorted(glob.glob(os.path.join(
            ROOT, "experiments/103_defended_maker/results/defended_maker_HL_*_inv_qf0.5.json"))):
        d = json.load(open(f))
        if d["asset"] == "HL_LINK":
            continue
        v.append(d["configs"][cfg][key]); c.append(d["asset"])
    return v, c


def exp111(window, cfg="micro_k1", key="gross_pnl_liq_day", per_day=True):
    """Basket (sum across coins) per day, or per-coin-day values."""
    import collections
    by = collections.defaultdict(dict)
    for f in sorted(glob.glob(os.path.join(
            ROOT, "experiments/111_fair_value_wide/results/fair_value_HL_*.json"))):
        d = json.load(open(f))
        if not d["date"].startswith(window):
            continue
        if cfg in d["runs"]:
            by[d["date"]][d["asset"]] = d["runs"][cfg][key]
    if per_day:
        return [sum(v.values()) for _, v in sorted(by.items())]
    vals, coins = [], []
    for dt, v in sorted(by.items()):
        for a, x in v.items():
            vals.append(x); coins.append(a)
    return vals, coins


def fmt(r, unit="", dec=2):
    lo, hi = r["ci"]
    sign = "" if lo * hi > 0 else "  **spans 0**"
    return (f"{r['mean']:+.{dec}f}{unit} | [{lo:+.{dec}f}, {hi:+.{dec}f}]{unit}{sign} "
            f"| {r['n']}")


